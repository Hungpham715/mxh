"""Source inventory and coverage report (selected subset vs eligible universe), from files only."""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

from src.common import PROCESSED, RAW, REJECTED, read_jsonl


def _rows(path: Path) -> list[dict[str, Any]]:
    return read_jsonl(path) if path.exists() else []


def run_coverage(out_path: Path) -> int:
    manifest = json.loads((PROCESSED / "manifest.json").read_text(encoding="utf-8"))
    acl_stats = _rows(RAW / "acl_selection_stats.jsonl")
    acl_selected = _rows(RAW / "acl_selected.jsonl")
    arxiv_selected = _rows(RAW / "arxiv_selected.jsonl")
    oa_works = _rows(RAW / "openalex_works.jsonl")
    oa_unmatched = _rows(RAW / "openalex_unmatched.jsonl")
    papers = _rows(PROCESSED / "papers.jsonl")
    authors = _rows(PROCESSED / "authors.jsonl")
    large = _rows(REJECTED / "large_author_papers.jsonl")

    acl_ids = [row.get("acl_id") or row.get("id") for row in acl_selected]
    arxiv_ids = [row.get("arxiv_id") or row.get("id") for row in arxiv_selected]
    by_kind_year = Counter((paper["source_kind"], paper["year"]) for paper in papers)
    selected_total = len(acl_selected) + len(arxiv_selected)
    normalized_total = len(papers)
    merged = manifest.get("normalize_stats", {}).get("arxiv_merged_into_acl", 0)

    lines = [
        "# Source inventory and coverage (generated by `python -m src.cli coverage`)",
        "",
        f"Scope `{manifest['scope_id']}`, snapshot created {manifest['created_at_utc']}. Every number below is "
        "read from `data/raw/*` and `data/processed/*`.",
        "",
        "## (i) Coverage of the SELECTED subset (target ≥ 99%)",
        "",
        "| Source | Selected | Downloaded raw | Normalized papers | Notes |",
        "|---|---:|---:|---:|---|",
        f"| ACL Anthology (6 volumes × 140) | {sum(r['selected'] for r in acl_stats)} | {len(acl_selected)} | "
        f"{sum(v for (k, _), v in by_kind_year.items() if k == 'acl')} | shortfall "
        f"{sum(r['shortfall'] for r in acl_stats)} |",
        f"| arXiv cs.CL (7 / month × 36) | {len(arxiv_selected)} | {len(arxiv_selected)} | "
        f"{sum(v for (k, _), v in by_kind_year.items() if k == 'arxiv')} | {merged} arXiv record(s) merged into "
        "their ACL version (same paper) |",
        f"| OpenAlex DOI enrichment | {len(oa_works)} lookups | "
        f"{sum(1 for r in oa_works if r.get('openalex'))} matched | — | {len(oa_unmatched)} unmatched kept with "
        "source metadata only |",
        "",
        f"Selected records = {selected_total}; normalized papers = {normalized_total}; "
        f"coverage of selected subset = **{normalized_total + merged}/{selected_total} = "
        f"{(normalized_total + merged) / selected_total:.2%}** (merged duplicates counted as covered). "
        f"Duplicate source IDs: ACL {len(acl_ids) - len(set(acl_ids))}, arXiv {len(arxiv_ids) - len(set(arxiv_ids))}.",
        "",
        "## (ii) Coverage of the ELIGIBLE universe (reported separately — this is a sample, not a census)",
        "",
        "| ACL volume | Eligible papers in volume | Selected | Sampling fraction |",
        "|---|---:|---:|---:|",
    ]
    eligible_total = 0
    for row in acl_stats:
        eligible_total += row["available"]
        lines.append(f"| {row['collection']}/{row['volume']} | {row['available']} | {row['selected']} | "
                     f"{row['selected'] / row['available']:.1%} |")
    lines += [
        f"| **total** | **{eligible_total}** | **{sum(r['selected'] for r in acl_stats)}** | "
        f"**{sum(r['selected'] for r in acl_stats) / eligible_total:.1%}** |",
        "",
        "arXiv cs.CL: the first 7 primary-cs.CL submissions per month are taken; the full monthly cs.CL volume "
        "(thousands per month) is not downloaded, so arXiv universe coverage is far below 1% and is NOT claimed.",
        "",
        "## Publication-year distribution (normalized papers)",
        "",
        "| Source | 2023 | 2024 | 2025 |",
        "|---|---:|---:|---:|",
    ]
    for kind in ("acl", "arxiv"):
        lines.append(f"| {kind} | " + " | ".join(str(by_kind_year.get((kind, y), 0)) for y in (2023, 2024, 2025)) + " |")
    status = Counter(author["identity_status"] for author in authors)
    lines += [
        "",
        "## Identity, rejects and quality flags",
        "",
        f"- Author identity status: {dict(status)}.",
        f"- Papers with > 20 authors held out of co-author cliques for manual review: {len(large)}.",
        f"- Normalization stats: {json.dumps(manifest.get('normalize_stats', {}), ensure_ascii=False)}.",
        f"- Topic status: {manifest.get('topic_status_counts')} (UNKNOWN = no precision-first rule fired; "
        "absence of a topic label is not evidence of absence).",
        "",
    ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"coverage report: {out_path}")
    return 0
